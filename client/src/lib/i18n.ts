const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, ru };

export function translate(
  locale: Locale,
  key: TranslationKey,
  variables?: Record<string, string | number>
): string {
  let value = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;

  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }

  return value;
}

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem('slopcall.lang');
    if (saved === 'en' || saved === 'ru') {
      return saved;
    }
  } catch {
    // localStorage can be unavailable; fall through to the system language.
  }

  const languages = [navigator.language, ...(navigator.languages ?? [])];
  return languages.some((language) => language.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
}

export function localeTag(locale: Locale): string {
  return locale === 'ru' ? 'ru-RU' : 'en-US';
}
